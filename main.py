
from math import isqrt  # Подключаем функцию для нахождения целого квадратного корня

# Лабораторная работа №2. Проверка характеристик нескольких чисел добавляем две новые возможности.
#1. После проверки числа программа спрашивает: «Проверить ещё одно число? (да/нет)». Если «да» — начинаем заново, если «нет» — завершаем программу.
#2. Проверяем, является ли число полным квадратом. Например, 49 = 7 × 7, значит, да. А 50 — нет.

while True:  # Главный цикл, позволяющий проверять несколько чисел

    # 1. Ввод числа с обработкой ошибок
    while True:  # Повторяем ввод, пока пользователь не введёт целое число
        try:  # Пробуем выполнить ввод
            number = int(input("Введите число: "))  # Вводим число и преобразуем его в целое
            break  # Выходим из внутреннего цикла при правильном вводе
        except ValueError:  # Перехватываем ошибку неправильного ввода
            print("Ошибка! Введите целое число.")  # Сообщаем об ошибке

    print(f"\nВаше число: {number}")  # Выводим введённое число

    # 2. Проверка знака числа
    if number > 0:  # Если число больше нуля
        print("Положительное: да")  # Число положительное
    elif number < 0:  # Если число меньше нуля
        print("Положительное: нет (отрицательное)")  # Число отрицательное
    else:  # Если число равно нулю
        print("Положительное: нет (ноль)")  # Число является нулём

    # 3. Проверка чётности
    if number % 2 == 0:  # Проверяем остаток от деления на 2
        print("Чётное: да")  # Число чётное
    else:  # Если остаток не равен нулю
        print("Чётное: нет")  # Число нечётное

    # 4. Проверка делимости на 3
    if number % 3 == 0:  # Если число делится на 3 без остатка
        print("Делится на 3: да")  # Выводим да
    else:  # Если есть остаток
        print("Делится на 3: нет")  # Выводим нет

    # 5. Проверка делимости на 5
    if number % 5 == 0:  # Если число делится на 5 без остатка
        print("Делится на 5: да")  # Выводим да
    else:  # Если есть остаток
        print("Делится на 5: нет")  # Выводим нет

    # 6. Проверка простого числа
    is_prime = number > 1  # Простым может быть только число больше 1
    divisor = 2  # Начинаем проверку делителей с двойки

    while divisor * divisor <= number and is_prime:  # Проверяем делители до квадратного корня
        if number % divisor == 0:  # Если нашли делитель без остатка
            is_prime = False  # Значит, число не простое
        divisor += 1  # Увеличиваем делитель на единицу

    if is_prime:  # Если число простое
        print("Простое: да")  # Выводим да
    else:  # Если число не простое
        print("Простое: нет")  # Выводим нет

    # 7. Количество цифр
    digits = len(str(abs(number)))  # Убираем минус, превращаем в строку и считаем цифры
    print(f"Количество цифр: {digits}")  # Выводим количество цифр

    # 8. Проверка полного квадрата (новое задание)
    if number >= 0:  # Проверяем, что число не отрицательное
        root = isqrt(number)  # Находим целый квадратный корень
        if root * root == number:  # Проверяем, равен ли квадрат корня числу
            print("Полный квадрат: да")  # Число является полным квадратом
        else:  # Если квадрат корня не равен числу
            print("Полный квадрат: нет")  # Число не является полным квадратом
    else:  # Если число отрицательное
        print("Полный квадрат: нет")  # Отрицательное число не может быть квадратом целого

    # 9. Повторная проверка числа (новое задание)
    while True:  # Повторяем вопрос при неправильном ответе
        answer = input("\nПроверить ещё одно число? (да/нет): ").strip().lower()  # Получаем ответ и приводим к нижнему регистру

        if answer == "да" or answer == "нет":  # Проверяем правильность ответа
            break  # Выходим из цикла вопроса
        else:  # Если введено что-то другое
            print("Ошибка! Введите да или нет.")  # Просим ответить правильно

    if answer == "нет":  # Если пользователь больше не хочет проверять числа
        print("Программа завершена.")  # Выводим сообщение
        break  # Завершаем главный цикл

    print()  # Делаем пустую строку перед следующим числом
