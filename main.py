
# Вариант 3. Проверка характеристик числа.
#  Нужно написать консольную программу, в которую пользователь вводит одно целое число, а программа рассказывает о нём всё необходимое.

while True:  # Запускаем бесконечный цикл для ввода числа
    try:  # Пробуем выполнить код, в котором возможна ошибка
        number = int(input("Введите целое число: "))  # Просим ввести число и преобразуем его в целое
        break  # Выходим из цикла, если число введено правильно
    except ValueError:  # Перехватываем ошибку, если введено не целое число
        print("Ошибка! Введите целое число.")  # Выводим сообщение об ошибке

print(f"\nВаше число: {number}")  # Выводим введённое число

# 1. Проверяем знак числа
if number > 0:  # Если число больше нуля
    print("Число: положительное")  # Выводим, что число положительное
elif number < 0:  # Иначе проверяем, меньше ли число нуля
    print("Число: отрицательное")  # Выводим, что число отрицательное
else:  # Если число не больше и не меньше нуля
    print("Число: ноль")  # Значит, число равно нулю

# 2. Проверяем чётность числа
if number % 2 == 0:  # Если остаток от деления на 2 равен нулю
    print("Чётное: да")  # Число чётное
else:  # Если остаток от деления не равен нулю
    print("Чётное: нет")  # Число нечётное

# 3. Проверяем делимость на 3
if number % 3 == 0:  # Проверяем, делится ли число на 3 без остатка
    print("Делится на 3: да")  # Число делится на 3
else:  # Если число делится с остатком
    print("Делится на 3: нет")  # Число не делится на 3

# 4. Проверяем делимость на 5
if number % 5 == 0:  # Проверяем, делится ли число на 5 без остатка
    print("Делится на 5: да")  # Число делится на 5
else:  # Если при делении есть остаток
    print("Делится на 5: нет")  # Число не делится на 5

# 5. Проверяем, является ли число простым
is_prime = number > 1  # Простым может быть только число больше 1

divisor = 2  # Начинаем проверять делители с числа 2

while divisor * divisor <= number and is_prime:  # Проверяем делители до квадратного корня из числа
    if number % divisor == 0:  # Если число делится на делитель без остатка
        is_prime = False  # Число не простое, так как найден делитель
    divisor += 1  # Увеличиваем делитель на единицу

if is_prime:  # Если число оказалось простым
    print("Простое: да")  # Выводим положительный результат
else:  # Если число не является простым
    print("Простое: нет")  # Выводим отрицательный результат

# 6. Считаем количество цифр
digits = len(str(abs(number)))  # Убираем минус, превращаем число в строку и считаем цифры
print(f"Количество цифр: {digits}")  # Выводим количество цифр
