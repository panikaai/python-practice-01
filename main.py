from math import isqrt  # Подключаем целый квадратный корень, как во второй практике.
import argparse  # Подключаем разбор аргументов командной строки.
import sys  # Подключаем доступ к аргументам запуска и сообщениям об ошибках.
from datetime import datetime  # Подключаем получение даты и времени.
from pathlib import Path  # Подключаем работу с путём к файлу журнала.


LOG_FILE = Path(__file__).with_name("errors.log")  # Журнал ошибок находится рядом с main.py.


def log_error(error, operation):  # Функция записи ошибки в файл.
    time_text = datetime.now().strftime("%Y-%m-%d %H:%M:%S")  # Получаем текущие дату и время.
    error_type = type(error).__name__  # Узнаём название типа ошибки.
    try:  # Пытаемся открыть файл журнала.
        with open(LOG_FILE, "a", encoding="utf-8") as file:  # Режим a добавляет запись и сохраняет старые.
            file.write(f"[{time_text}] {error_type}:\n")  # Записываем дату, время и тип исключения.
            file.write(f"Описание: {error}\n")  # Записываем описание исключения.
            file.write(f"Операция: {operation}\n\n")  # Записываем, где произошла ошибка.
    except OSError as file_error:  # Обрабатываем ситуацию, когда нельзя записать журнал.
        print(f"Не удалось записать ошибку в errors.log: {file_error}", file=sys.stderr)  # Показываем проблему пользователю.


class LoggingArgumentParser(argparse.ArgumentParser):  # Стандартный argparse с записью ошибок запуска. наследуется от готового класса
    def error(self, message):  # Этот метод вызывается при неверных аргументах.
        error = ValueError(message)  # Создаём понятное описание ошибки аргументов.
        log_error(error, f"Аргументы запуска: {' '.join(sys.argv[1:])}")  # Записываем ошибку и команду запуска.
        super().error(message)  # Выводим пользователю ошибку и подсказку из argparse.


def main():  # Главная функция программы.
    parser = LoggingArgumentParser(description="Практическая №3. Вариант 3: характеристики числа.")  # Создаём обработчик аргументов командной строки.
    #отвечает за получение аргументов командной строки и обработку ошибок.
    parser.add_argument("number", nargs="?", help="Целое число для анализа, например 49.")  # Позиционный аргумент числа; без него работает старый режим.
    parser.add_argument("--prime", action="store_true", help="Проверить, является ли число простым.")  # Флаг проверки простого числа.
    parser.add_argument("--even", action="store_true", help="Проверить чётность числа.")  # Флаг чётности.
    parser.add_argument("--square", action="store_true", help="Проверить, является ли число полным квадратом.")  # Флаг полного квадрата.
    parser.add_argument("--all", action="store_true", help="Вывести все характеристики числа.")  # Флаг полного анализа.
    arguments = parser.parse_args()  # Метод parse_args() считывает аргументы командной строки и сохраняет их в объект arguments.

    if arguments.number is None and (arguments.prime or arguments.even or arguments.square or arguments.all):  # Проверяем, не забыли ли число перед флагами.
        parser.error("Укажите число перед флагами, например: python main.py 49 --prime")  # Сообщаем об ошибке и записываем её в журнал.

    if arguments.number is not None:  # Если число указали при запуске, используем новый режим.
        try:  # Пробуем преобразовать аргумент и проверить число.
            number = int(arguments.number)  # Преобразуем позиционный аргумент в целое число.
            all_checks = arguments.all or not (arguments.prime or arguments.even or arguments.square)  # Определяем, нужен ли полный анализ.
            print(f"Number: {number}")  # Выводим число, которое проверяем.

            if all_checks:  # Полный анализ включает проверку знака числа.
                print(f"Positive: {'Yes' if number > 0 else 'No'}")  # Показываем, положительное ли число.

            if all_checks or arguments.even:  # Проверяем чётность, если она запрошена.
                print(f"Even: {'Yes' if number % 2 == 0 else 'No'}")  # Выводим чётность числа.

            if all_checks:  # При полном анализе проверяем делимость на 3 и 5.
                print(f"Divisible by 3: {'Yes' if number % 3 == 0 else 'No'}")  # Проверяем делимость на 3.
                print(f"Divisible by 5: {'Yes' if number % 5 == 0 else 'No'}")  # Проверяем делимость на 5.

            if all_checks or arguments.prime:  # Выполняем проверку простого числа, если она нужна.
                is_prime = number > 1  # Простым может быть только число больше единицы.
                divisor = 2  # Начинаем поиск делителей с двойки.
                while divisor * divisor <= number and is_prime:  # Перебираем делители до квадратного корня, как в старом коде.
                    if number % divisor == 0:  # Если число делится на делитель без остатка.
                        is_prime = False  # Значит, число не простое.
                    divisor += 1  # Переходим к следующему делителю.
                print(f"Prime: {'Yes' if is_prime else 'No'}")  # Выводим результат проверки простоты.

            if all_checks or arguments.square:  # Выполняем проверку полного квадрата, если она нужна.
                if number >= 0:  # Проверяем, что число не отрицательное.
                    root = isqrt(number)  # Находим целый квадратный корень.
                    is_square = root * root == number  # Проверяем, совпадает ли квадрат корня с числом.
                else:  # Если число отрицательное.
                    is_square = False  # Отрицательное число не бывает полным квадратом целого.
                print(f"Perfect square: {'Yes' if is_square else 'No'}")  # Выводим результат проверки квадрата.

            if all_checks:  # При полном анализе считаем количество цифр.
                digits = len(str(abs(number)))  # Убираем знак, преобразуем в строку и считаем цифры.
                print(f"Number of digits: {digits}")  # Выводим количество цифр.
            return  # После проверки в командной строке завершаем программу.

        except ValueError as error:  # Обрабатываем неправильное число, например abc.
            log_error(error, f"Преобразование числа из командной строки: {arguments.number!r}")  # Записываем ошибку в журнал.
            print("Ошибка: введите целое число, например 49 или -12.")  # Выводим понятное сообщение.
            return  # Завершаем неверный запуск.
        except ZeroDivisionError as error:  # Защита от деления на ноль при будущих изменениях вычислений.
            log_error(error, f"Проверка числа {arguments.number} через командную строку")  # Сохраняем математическую ошибку.
            print("Ошибка: деление на ноль невозможно.")  # Объясняем ошибку пользователю.
            return  # Завершаем проверку.
        except ArithmeticError as error:  # Обрабатываем другие арифметические ошибки.
            log_error(error, f"Проверка числа {arguments.number} через командную строку")  # Сохраняем ошибку.
            print(f"Ошибка вычисления: {error}")  # Выводим понятное сообщение.
            return  # Завершаем проверку.

    # Ниже — прежняя программа из практической №2 без изменения алгоритма проверок.
    if arguments.number is None:  # Без аргументов работаем через обычный ввод, как раньше.
        while True:  # Главный цикл, позволяющий проверять несколько чисел

            # 1. Ввод числа с обработкой ошибок
            while True:  # Повторяем ввод, пока пользователь не введёт целое число
                try:  # Пробуем выполнить ввод
                    number = int(input("Введите число: "))  # Вводим число и преобразуем его в целое
                    break  # Выходим из внутреннего цикла при правильном вводе
                except ValueError as error:  # Перехватываем ошибку неправильного ввода
                    log_error(error, "Ввод числа через клавиатуру")  # Записываем ошибку в errors.log
                    print("Ошибка! Введите целое число.")  # Сообщаем об ошибке

            print(f"\nВаше число: {number}")  # Выводим введённое число

            # 2. Проверка знака числа
            if number > 0:  # Если число больше нуля
                print("Положительное: да")  # Число положительное
            elif number < 0:  # Если число меньше нуля
                print("Положительное: нет (отрицательное)")  # Число отрицательное
            else:  # Если число равно нулю
                print("Положительное: нет (ноль)")  # Число является нулём

            # 3. Проверка чётности
            if number % 2 == 0:  # Проверяем остаток от деления на 2
                print("Чётное: да")  # Число чётное
            else:  # Если остаток не равен нулю
                print("Чётное: нет")  # Число нечётное

            # 4. Проверка делимости на 3
            if number % 3 == 0:  # Если число делится на 3 без остатка
                print("Делится на 3: да")  # Выводим да
            else:  # Если есть остаток
                print("Делится на 3: нет")  # Выводим нет

            # 5. Проверка делимости на 5
            if number % 5 == 0:  # Если число делится на 5 без остатка
                print("Делится на 5: да")  # Выводим да
            else:  # Если есть остаток
                print("Делится на 5: нет")  # Выводим нет

            # 6. Проверка простого числа
            is_prime = number > 1  # Простым может быть только число больше 1
            divisor = 2  # Начинаем проверку делителей с двойки

            while divisor * divisor <= number and is_prime:  # Проверяем делители до квадратного корня
                if number % divisor == 0:  # Если нашли делитель без остатка
                    is_prime = False  # Значит, число не простое
                divisor += 1  # Увеличиваем делитель на единицу

            if is_prime:  # Если число простое
                print("Простое: да")  # Выводим да
            else:  # Если число не простое
                print("Простое: нет")  # Выводим нет

            # 7. Количество цифр
            digits = len(str(abs(number)))  # Убираем минус, превращаем в строку и считаем цифры
            print(f"Количество цифр: {digits}")  # Выводим количество цифр

            # 8. Проверка полного квадрата (новое задание)
            if number >= 0:  # Проверяем, что число не отрицательное
                root = isqrt(number)  # Находим целый квадратный корень
                if root * root == number:  # Проверяем, равен ли квадрат корня числу
                    print("Полный квадрат: да")  # Число является полным квадратом
                else:  # Если квадрат корня не равен числу
                    print("Полный квадрат: нет")  # Число не является полным квадратом
            else:  # Если число отрицательное
                print("Полный квадрат: нет")  # Отрицательное число не может быть квадратом целого

            # 9. Повторная проверка числа (новое задание)
            while True:  # Повторяем вопрос при неправильном ответе
                answer = input("\nПроверить ещё одно число? (да/нет): ").strip().lower()  # Получаем ответ и приводим к нижнему регистру

                if answer == "да" or answer == "нет":  # Проверяем правильность ответа
                    break  # Выходим из цикла вопроса
                else:  # Если введено что-то другое
                    log_error(ValueError(f"Неверный ответ: {answer!r}"), "Ответ на вопрос о повторной проверке")  # Сохраняем неправильный ответ
                    print("Ошибка! Введите да или нет.")  # Просим ответить правильно

            if answer == "нет":  # Если пользователь больше не хочет проверять числа
                print("Программа завершена.")  # Выводим сообщение
                break  # Завершаем главный цикл

            print()  # Делаем пустую строку перед следующим числом


if __name__ == "__main__":  # Запускаем программу только при прямом открытии main.py.
    try:  # Перехватываем неожиданные ошибки ввода и прерывания работы.
        main()  # Запускаем программу.
    except EOFError as error:  # Обрабатываем отсутствие необходимых данных при вводе.
        log_error(error, "Ввод данных с клавиатуры неожиданно завершился")  # Записываем ошибку в журнал.
        print("\nОшибка: ввод завершился до получения необходимых данных.")  # Показываем понятное сообщение.
    except KeyboardInterrupt:  # Обрабатываем нажатие Ctrl+C.
        print("\nПрограмма остановлена пользователем.")  # Выводим сообщение вместо технической ошибки.
    except ZeroDivisionError as error:  # Обрабатываем возможное деление на ноль.
        log_error(error, "Вычисление характеристик числа")  # Записываем тип и описание математической ошибки.
        print("Ошибка: деление на ноль невозможно.")  # Сообщаем пользователю об ошибке.
    except Exception as error:  # Перехватываем прочие неожиданные ошибки.
        log_error(error, "Работа программы")  # Сохраняем ошибку с датой и контекстом.
        print(f"Во время работы программы возникла ошибка: {error}")  # Выводим понятное описание.
